#!/usr/bin/env bash
# The LoRA-delta purity gate (r318, GitHub issue #331).
#
# WHY THIS EXISTS
#   The decode Q8_1 MUL fusion (`ggml_cuda_op_unary_mul_q8_1`, the silu/sigmoid/softplus -> MUL ->
#   matmul chain) replaces the F32 MUL output with the matmul's Q8_1 activation: it writes ONLY the
#   Q8_1 blocks and never the F32 tensor the node was declared to produce.  That is safe exactly as
#   long as nothing else reads that F32 buffer.  The matcher counted only DIRECT `src == mul` readers,
#   so a reader that reaches the MUL through a reshape (the matmul itself does, because mmvq wants a 2-D
#   activation) was invisible.  `llama_graph_context::build_lora_mm()` appends a LoRA `MUL_MAT` that
#   reads the SAME activation, so on a model with a LoRA on `ffn_down` (whose input is silu(gate)*up)
#   or on `ssm_out` (whose input is norm*silu(z) in the GDN layers) the LoRA delta was computed from a
#   buffer nobody wrote.  The adapter loads, `/lora-adapters` reports the scale, and the model behaves
#   as if it were absent -- which is exactly the report: "silently ignored unless
#   GGML_CUDA_DISABLE_FUSION=1".
#
#   The fix counts readers THROUGH VIEWS (`ggml_cuda_count_uses`), i.e. the fused chain must own every
#   reader: 1 direct (matmul) or 2 (reshape + matmul through it).  A LoRA-free graph reads exactly that,
#   so the fusion still fires there; a LoRA graph reads more and the fusion stands down, leaving the
#   unfused chain (which writes the F32 activation and lets the matmul quantize it) to run.
#
# WHAT IT CHECKS (one 4B model, one GPU, same-seed greedy text)
#   A. `ref` (no LoRA, fusions on) == `refoff` (no LoRA, `GGML_CUDA_DISABLE_FUSION=1`): the unfused chain
#      is the oracle, and this is the arm that proves the oracle is exact on this model.
#   B. `loraon` == `loraoff`: the LoRA arm with the delivery's default fusions must reproduce the LoRA
#      arm with every fusion off, byte for byte.  This is the fix's whole claim.
#   C. `loraon` != `ref`: NON-VACUITY.  If the adapter does not move the text, B is trivially true and
#      the arm proves nothing (a wrong-alpha or unaddressable adapter would do exactly that).
#   D. MECHANISM: with `GGML_CUDA_FUSE_TRACE=1` the LoRA arm must log at least one
#      `FUSE_TRACE MUL_Q8_1 DECLINE ne=... readers=... want=...` line, i.e. the matcher really reached a
#      MUL with extra readers and the new count is what declined it; the SAME arm without a LoRA must
#      log NONE, i.e. the fix does not disable the fusion generally (only the unsafe shape).
#   E. The prefill/long-prompt half (`-ub 512`, a ~2k-token prompt, `-c 8192`): repeats B and C at a
#      ubatch where the PREFILL fusions run (`GGML_CUDA_FUSE_SWIGLU_MMQ` and the GLU -> Q8_1 marker), so a
#      delta dropped while the prompt is ingested would change the KV and therefore the generated text.
#      Keep it even though the decode fusion alone already moves this arm pre-fix: it is the only arm here
#      that builds a 512-token prefill graph with an adapter loaded.
#
#   Negative-tested (r318): the pre-fix build fails B, D and E on this gate's own synthetic adapter
#   (`04ea54ab3e38` fused vs `fe967e92321a` unfused), and on the 27B Qwen3.8 `abliteration-lora.gguf` of
#   the issue (`f3e8501e7b38` vs `f7026ffb399a`).
#
# Usage:
#   ./gate-lora-fusion.sh
#   ./gate-lora-fusion.sh --no-faults
# Environment:
#   BUILD_DIR    llama.cpp build tree   (default: ~/llama.cpp/build-rocm)
#   LLAMA_CLI    llama-cli              (default: $BUILD_DIR/bin/llama-cli)
#   MODEL        a model GGUF           (default: Qwen3.5-4B Q8_0 -- dense+GDN, has ffn_down and ssm_out)
#   LORA         a LoRA GGUF            (default: generated by scripts/make-test-lora.py into $KEEPOUT)
#   MODULES      modules the generated adapter targets (default: ffn_down,ssm_out,attn_output)
#   LORA_STD     stddev of the generated adapter (default: 0.05)
#   GPU          HIP_VISIBLE_DEVICES to pin (default: 0)
#   NGEN         generated tokens       (default: 40)
#   CTX          context size           (default: 4096, the decode arms)
#   UB           decode ubatch          (default: 1)
#   PREFILL_UB   prefill arm's ubatch   (default: 512)
#   PREFILL_CTX  context size for the prefill arms (default: 8192)
#   PROMPT       the decode prompt      (default: below)
#   PREFILL_PROMPT  the prefill prompt  (default: the first PREFILL_CHARS bytes of
#                   prompts/prose-rdna-boosts.txt, so it fits PREFILL_CTX; a run that overruns
#                   its context aborts and echoes the prompt, which FAILS the arm rather than
#                   quietly comparing two echoes)
#   PREFILL_CHARS  bytes of that file to take (default: 9000)
#   KEEPOUT      dir for the logs       (default: mktemp -d)
#   TIME_LIMIT   per llama-cli timeout  (default: 1200 s)
#   D_ARM=0 / E_ARM=0 disables the mechanism / prefill arms.
set -uo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$HOME/llama.cpp/build-rocm}"
LLAMA_CLI="${LLAMA_CLI:-$BUILD_DIR/bin/llama-cli}"
MODEL="${MODEL:-/llm/models/Qwen3.5/4B/Q8_0/Qwen3.5-4B-Q8_0.gguf}"
KEEPOUT="${KEEPOUT:-$(mktemp -d)}"
LORA="${LORA:-}"
MODULES="${MODULES:-ffn_down,ssm_out,attn_output}"
LORA_STD="${LORA_STD:-0.05}"
GPU="${GPU:-0}"
NGEN="${NGEN:-40}"
CTX="${CTX:-4096}"
UB="${UB:-1}"
PREFILL_UB="${PREFILL_UB:-512}"
PREFILL_CTX="${PREFILL_CTX:-8192}"
PREFILL_CHARS="${PREFILL_CHARS:-9000}"
PROMPT="${PROMPT:-Write a short technical note about how a hash table handles collisions, with a C example.}"
PREFILL_PROMPT="${PREFILL_PROMPT:-}"
TIME_LIMIT="${TIME_LIMIT:-1200}"
D_ARM="${D_ARM:-1}"
E_ARM="${E_ARM:-1}"

fails=0
fail() { echo "FAIL: $*"; fails=$((fails + 1)); }
note() { echo "    $*"; }

GATE_SINCE_TS="$(date -d '-1 second' '+%Y-%m-%d %H:%M:%S' 2>/dev/null || true)"

FAULTS=1
for a in "$@"; do
    case "$a" in
        --no-faults) FAULTS=0 ;;
        -h|--help) sed -n '2,/^set -uo/p' "$0" | sed 's/^# \{0,1\}//; /^set -uo/d'; exit 0 ;;
        *) echo "usage: $0 [--no-faults]" >&2; exit 2 ;;
    esac
done

echo "==> LoRA-delta purity gate (issue #331)"
echo "    build=$BUILD_DIR"
echo "    model=$MODEL"
echo "    logs=$KEEPOUT"
mkdir -p "$KEEPOUT"

[ -x "$LLAMA_CLI" ] || { echo "FAIL: llama-cli not executable: $LLAMA_CLI" >&2; exit 2; }
[ -f "$MODEL" ]     || { echo "FAIL: model not found: $MODEL (set MODEL)" >&2; exit 2; }

if [ -z "$LORA" ]; then
    LORA="$KEEPOUT/test-lora.gguf"
    LLAMA_DIR="${LLAMA_DIR:-$HOME/llama.cpp}" python3 "$REPO_DIR/scripts/make-test-lora.py" \
        "$MODEL" "$LORA" --modules "$MODULES" --std "$LORA_STD" 2>&1 | sed 's/^/    /' ||
        { echo "FAIL: could not generate the test adapter (scripts/make-test-lora.py)" >&2; exit 2; }
fi
[ -f "$LORA" ] || { echo "FAIL: adapter not found: $LORA" >&2; exit 2; }
echo "    lora=$LORA"

# run_arm <name> <ub> <lora:yes|no> <lv-args> [env assignments...] -- one armed llama-cli run.
# A TEXT arm passes no -lv at all (llama-cli's default is errors-only, so the stream carries only the
# generated text); a CENSUS arm passes `-lv 2` because the FUSE_TRACE line is a WARN (AGENTS.md, the
# -lv table), and its text is discarded.
run_arm() {
    local name="$1" ub="$2" use_lora="$3" lv="$4"; shift 4
    local lora_args=()
    local prompt="$PROMPT"
    local ctx="$CTX"
    [ "$use_lora" = yes ] && lora_args=(--lora "$LORA")
    if [ "$ub" = "$PREFILL_UB" ]; then
        prompt="$PREFILL_PROMPT"
        ctx="$PREFILL_CTX"
    fi
    env "$@" HIP_VISIBLE_DEVICES="$GPU" \
        timeout "$TIME_LIMIT" "$LLAMA_CLI" -m "$MODEL" -ngl 99 -fa on -c "$ctx" -ub "$ub" \
        "${lora_args[@]}" -p "$prompt" -n "$NGEN" --seed 42 --temp 0 \
        --no-display-prompt --single-turn $lv > "$KEEPOUT/$name.log" 2>&1
    local rc=$?
    local got
    got="$(python3 "$REPO_DIR/scripts/extract-generated.py" "$KEEPOUT/$name.log" 2>/dev/null |
        sed -n 's/^\([0-9]*\) chars sha=\([0-9a-f]*\)$/\1 \2/p' | head -1)"
    echo "    $name: exit $rc, ${got:-no text extracted}"
    ARM_HASH="${got##* }"
    ARM_CHARS="${got%% *}"
    ARM_RC="$rc"
    # An arm that overran its context (or otherwise failed to generate) echoes the prompt and exits
    # non-zero; comparing two echoes would look like a pass, so it is a FAIL by itself.
    if [ "$rc" != 0 ]; then
        fail "$name exited $rc (log: $KEEPOUT/$name.log)"
    elif grep -q 'exceeds the available context size' "$KEEPOUT/$name.log"; then
        fail "$name overran its context (-c $ctx) and echoed the prompt instead of generating (log: $KEEPOUT/$name.log)"
    fi
    ARM_OK=1
    [ "$rc" = 0 ] && ! grep -q 'exceeds the available context size' "$KEEPOUT/$name.log" || ARM_OK=0
}

hash_of() { printf '%s' "$1"; }

if [ -z "$PREFILL_PROMPT" ] && [ -f "$REPO_DIR/prompts/prose-rdna-boosts.txt" ]; then
    PREFILL_PROMPT="$(head -c "$PREFILL_CHARS" "$REPO_DIR/prompts/prose-rdna-boosts.txt")"
fi
[ -n "$PREFILL_PROMPT" ] || fail "no prefill prompt: set PREFILL_PROMPT or keep prompts/prose-rdna-boosts.txt"

echo
echo "--- A/B/C: decode (ub=$UB, $NGEN tokens)"
run_arm ref      "$UB" no   ""
ref_hash="$ARM_HASH"
run_arm refoff   "$UB" no   "" GGML_CUDA_DISABLE_FUSION=1
refoff_hash="$ARM_HASH"
run_arm loraon   "$UB" yes  ""
loraon_hash="$ARM_HASH"
run_arm loraoff  "$UB" yes  "" GGML_CUDA_DISABLE_FUSION=1
loraoff_hash="$ARM_HASH"

[ -n "$ref_hash" ] && [ -n "$loraon_hash" ] && [ -n "$loraoff_hash" ] ||
    fail "a decode arm produced no extractable text (see $KEEPOUT)"
if [ -n "$ref_hash" ] && [ "$ref_hash" != "$refoff_hash" ]; then
    fail "A: the no-LoRA fused text ($ref_hash) != the unfused chain ($refoff_hash) -- the oracle is not exact here, so the rest of this gate cannot be judged"
else
    note "A: no-LoRA fused == unfused ($ref_hash)"
fi
if [ -n "$loraon_hash" ] && [ "$loraon_hash" != "$loraoff_hash" ]; then
    fail "B: the LoRA arm with fusions ON ($loraon_hash) != with fusions OFF ($loraoff_hash) -- a fused launch is still dropping the adapter's delta"
else
    note "B: LoRA fused == unfused ($loraon_hash)"
fi
if [ -n "$ref_hash" ] && [ -n "$loraon_hash" ] && [ "$ref_hash" = "$loraon_hash" ]; then
    fail "C: the LoRA changed nothing ($ref_hash == $loraon_hash) -- the arm is vacuous (adapter not applied?)"
else
    note "C: the adapter moves the text ($ref_hash -> $loraon_hash)"
fi

if [ "$D_ARM" = 1 ]; then
    echo
    echo "--- D: mechanism (FUSE_TRACE)"
    run_arm trace_lora   "$UB" yes "-lv 2" GGML_CUDA_FUSE_TRACE=1
    run_arm trace_nolora "$UB" no  "-lv 2" GGML_CUDA_FUSE_TRACE=1
    n_lora="$(grep -c 'FUSE_TRACE MUL_Q8_1 DECLINE' "$KEEPOUT/trace_lora.log")"
    n_nolora="$(grep -c 'FUSE_TRACE MUL_Q8_1 DECLINE' "$KEEPOUT/trace_nolora.log")"
    note "declines: LoRA=$n_lora no-LoRA=$n_nolora"
    [ "${n_lora:-0}" -ge 1 ] ||
        fail "D: the LoRA arm logged no 'FUSE_TRACE MUL_Q8_1 DECLINE' line -- it never reached a MUL with an extra reader, so B is vacuous (log: $KEEPOUT/trace_lora.log)"
    [ "${n_nolora:-0}" -eq 0 ] ||
        fail "D: the no-LoRA arm logged $n_nolora decline(s) -- the new reader count must not change a LoRA-free decision (log: $KEEPOUT/trace_nolora.log)"
    if [ "${n_lora:-0}" -ge 1 ]; then
        note "trace: $(sed -n 's/.*FUSE_TRACE MUL_Q8_1 DECLINE \(.*\)/\1/p' "$KEEPOUT/trace_lora.log" | sort -u | tr '\n' ' ')"
    fi
fi

if [ "$E_ARM" = 1 ]; then
    echo
    echo "--- E: prefill (ub=$PREFILL_UB)"
    run_arm p_ref     "$PREFILL_UB" no  ""
    p_ref_hash="$ARM_HASH"
    run_arm p_loraon  "$PREFILL_UB" yes ""
    p_loraon_hash="$ARM_HASH"
    run_arm p_loraoff "$PREFILL_UB" yes "" GGML_CUDA_DISABLE_FUSION=1
    p_loraoff_hash="$ARM_HASH"
    if [ -n "$p_loraon_hash" ] && [ "$p_loraon_hash" != "$p_loraoff_hash" ]; then
        fail "E: prefill: LoRA fused ($p_loraon_hash) != unfused ($p_loraoff_hash)"
    else
        note "E: prefill LoRA fused == unfused ($p_loraon_hash)"
    fi
    if [ -n "$p_ref_hash" ] && [ -n "$p_loraon_hash" ] && [ "$p_ref_hash" = "$p_loraon_hash" ]; then
        fail "E: prefill: the adapter changed nothing ($p_ref_hash == $p_loraon_hash) -- the arm is vacuous"
    else
        note "E: prefill: the adapter moves the text ($p_ref_hash -> $p_loraon_hash)"
    fi
fi

if [ "$FAULTS" = 1 ] && [ -x "$REPO_DIR/scripts/check-gpu-faults.sh" ] && [ -n "$GATE_SINCE_TS" ]; then
    echo
    echo "--- GPU faults over this gate's window"
    if "$REPO_DIR/scripts/check-gpu-faults.sh" --since "$GATE_SINCE_TS" >> "$KEEPOUT/faults.log" 2>&1; then
        note "clean"
    else
        fail "check-gpu-faults.sh reported a fault (see $KEEPOUT/faults.log)"
    fi
fi

echo
if [ "$fails" -eq 0 ]; then
    echo "==> PASS: LoRA delta survives the fused chain (decode + prefill), fusions still fire without an adapter"
    echo "    logs: $KEEPOUT"
    exit 0
fi
echo "==> FAIL: $fails check(s) failed; logs: $KEEPOUT"
exit 1
